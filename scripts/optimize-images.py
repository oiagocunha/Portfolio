"""Generate WebP variants of the site images and the manifest the components read.

Usage (from the repository root, needs Python 3 with Pillow):
    python scripts/optimize-images.py

For each image below it writes public/images/<name>-<width>.webp for every target
width that is not larger than the original, then rewrites src/lib/image-variants.ts.
Re-run it after adding or replacing an image and commit the outputs.
"""

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
IMAGES = ROOT / "public" / "images"
MANIFEST = ROOT / "src" / "lib" / "image-variants.ts"

SCREENSHOT_WIDTHS = [480, 960, 1280]
TARGETS = {
    "Perfil.jpg": [192, 384],
    "Conquista.png": [320, 640],
    "fv-croche.png": SCREENSHOT_WIDTHS,
    "lead-pilot.png": SCREENSHOT_WIDTHS,
    "agenda-flow.png": SCREENSHOT_WIDTHS,
    "assist-ia.png": SCREENSHOT_WIDTHS,
    "assistente-corporativo.jpg": SCREENSHOT_WIDTHS,
    "public-data-monitor-swagger.png": SCREENSHOT_WIDTHS,
    "job-match-alerts-swagger.png": SCREENSHOT_WIDTHS,
}


def main() -> None:
    manifest: dict[str, list[int]] = {}
    for name, widths in TARGETS.items():
        source = IMAGES / name
        with Image.open(source) as image:
            image = image.convert("RGBA" if image.mode in ("RGBA", "LA", "P") else "RGB")
            produced = []
            for width in widths:
                if width > image.width:
                    continue
                height = round(image.height * width / image.width)
                resized = image.resize((width, height), Image.LANCZOS)
                target = IMAGES / f"{source.stem}-{width}.webp"
                resized.save(target, "WEBP", quality=80, method=6)
                produced.append(width)
                print(f"{target.relative_to(ROOT)}  {target.stat().st_size // 1024} KB")
        manifest[f"/images/{name}"] = produced

    lines = [
        "// Generated by scripts/optimize-images.py. Do not edit by hand.",
        "/** WebP widths available for each original image, as `<name>-<width>.webp`. */",
        "export const imageVariants: Record<string, number[]> = {",
        *[f'  "{src}": [{", ".join(map(str, widths))}],' for src, widths in manifest.items()],
        "};",
        "",
    ]
    MANIFEST.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {MANIFEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
